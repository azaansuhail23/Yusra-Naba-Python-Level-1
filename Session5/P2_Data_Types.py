# Single Value Data type: It contains one value at a time. 

# 1. Integer (int)
age=8
print(age)
print(type(age))

# 2. Float (float)
weight=70.45
print(weight)
print(type(weight))

# 3. String (str)
name="Umaiza"
print(name)
print(type(name))

# 4. Boolean (bool)
isRaining=True
print(isRaining)
print(type(isRaining))

